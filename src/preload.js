'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('meter', {
  init: () => ipcRenderer.invoke('init'),
  focus: (s) => ipcRenderer.invoke('focus', { pid: s.pid, cwd: s.cwd }),
  refreshUsage: () => ipcRenderer.send('usage:refresh'),
  saveTodos: (todos) => ipcRenderer.send('todos:save', todos),
  savePrefs: (patch) => ipcRenderer.send('prefs:save', patch),
  moveTo: (x, y) => ipcRenderer.send('move', x, y),
  setWidth: (width) => ipcRenderer.send('width', width),
  setCompact: (on) => ipcRenderer.send('compact', on),
  setPinned: (on) => ipcRenderer.send('pin', on),
  answer: (a) => ipcRenderer.send('ask:answer', a),
  askSize: (height) => ipcRenderer.send('ask:size', height),
  askDone: () => ipcRenderer.send('ask:done'),
  quit: () => ipcRenderer.send('quit'),
  jiraRefresh: () => ipcRenderer.invoke('jira:refresh'),
  jiraSuggest: () => ipcRenderer.invoke('jira:suggest'),
  jiraSignIn: () => ipcRenderer.invoke('jira:signin'),
  jiraSite: (id) => ipcRenderer.invoke('jira:site', id),
  jiraConnect: (form) => ipcRenderer.invoke('jira:connect', form),
  jiraForget: () => ipcRenderer.invoke('jira:forget'),
  openUrl: (url) => ipcRenderer.send('open-url', url),
  jiraTransitions: (key) => ipcRenderer.invoke('jira:transitions', key),
  jiraTransition: (key, id) => ipcRenderer.invoke('jira:transition', key, id),
  jiraEdit: (key, change) => ipcRenderer.invoke('jira:edit', key, change),
  jiraCreate: (todo) => ipcRenderer.invoke('jira:create', todo),
  copy: (text) => ipcRenderer.send('copy', text),
  plan: (item, change) => ipcRenderer.invoke('plan', item, change),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  projectsRefresh: (list) => ipcRenderer.invoke('projects:refresh', list),
  saveProjects: (list) => ipcRenderer.send('projects:save', list),
  boardSet: (url) => ipcRenderer.invoke('board:set', url),
  boardUpdate: (projects, todos) => ipcRenderer.invoke('board:update', projects, todos),
  onSessions: (cb) => ipcRenderer.on('sessions', (_e, list) => cb(list)),
  onUsage: (cb) => ipcRenderer.on('usage', (_e, u) => cb(u)),
  onShowTab: (cb) => ipcRenderer.on('show-tab', (_e, tab) => cb(tab)),
});
